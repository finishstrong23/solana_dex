// Generate a fake sparkline with a trend
function genSparkline(trend: "up" | "down" | "flat", volatility: number = 0.05): number[] {
  const points: number[] = [];
  let val = 1;
  for (let i = 0; i < 24; i++) {
    const noise = (Math.random() - 0.5) * volatility * 2;
    const drift = trend === "up" ? 0.015 : trend === "down" ? -0.015 : 0;
    val *= (1 + drift + noise);
    points.push(val);
  }
  return points;
}

